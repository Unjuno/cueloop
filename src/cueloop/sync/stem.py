"""Full-sentence "initial condition" cues (stem cues).

A bare cue ("根拠は？") names the missing operation only. A stem cue speaks a
complete, context-grounded sentence that embodies the operation, so the
speaker hears the shape of the clause they can adopt or adapt — e.g.
"根拠は、観測データでは弱い、からです。".

Stems are generated by a local OpenAI-compatible model. Any failure falls
back to a deterministic template built from the predicted span, and then to
the bare wording, so a stem session never stays silent just because the
model hiccuped.
"""

from __future__ import annotations

import json
import re
import urllib.request
from collections.abc import Sequence

from .predictors import PREFERRED_DECISION_MODELS, resolve_model

# Japanese instruction shown to the writer model for each operation. The stem
# must *embody* the move, not just name it.
OPERATION_INSTRUCTIONS: dict[str, str] = {
    "conclusion": "結論を述べる（いまの議論がどこに着地するか）",
    "ground": "根拠を述べる（その判断を支える理由・データ・事実）",
    "mechanism": "仕組み・理由を説明する（なぜそうなるのか）",
    "concretize": "具体例・具体的な場合を挙げる（抽象を具体に落とす）",
    "dependency": "前提・依存関係を述べる（何に依存して成り立つか）",
    "boundary": "条件・適用範囲・限界を述べる（どこまで成立するか）",
    "comparison": "比較対象と違いを述べる（何と比べてどう違うか）",
    "invert": "逆の場合を検討する（たら・ならの反対側）",
}

STEM_TEMPLATES: dict[str, tuple[str, ...]] = {
    "conclusion": ("結論としては、{span}です。",),
    "ground": ("根拠は、{span}からです。",),
    "mechanism": ("仕組みとしては、{span}からです。",),
    "concretize": ("具体的には、{span}です。",),
    "dependency": ("前提としては、{span}です。",),
    "boundary": ("条件としては、{span}です。",),
    "comparison": ("比べると、{span}です。",),
    "invert": ("逆に言うと、{span}です。",),
}

DEFAULT_STEM_MAX_CHARACTERS = 48
_SPAN_HEAD = 24

_WRAP_PAIRS = ("「」", "『』", "“”", "\"\"", "''")


def finalize_stem(text: str, *, max_characters: int = DEFAULT_STEM_MAX_CHARACTERS) -> str | None:
    """Normalize an LLM-written stem, or return None when unusable."""
    if not isinstance(text, str):
        return None
    sentence = re.sub(r"\s+", " ", text).strip()
    for pair in _WRAP_PAIRS:
        if len(sentence) >= 2 and sentence.startswith(pair[0]) and sentence.endswith(pair[1]):
            sentence = sentence[1:-1].strip()
    if not sentence:
        return None
    if any(token in sentence for token in ("{", "}", "```", "\n", "\r")):
        # JSON or markdown leakage, not a sentence.
        return None
    if len(sentence) > max_characters:
        return None
    if sentence[-1] not in "。！？":
        sentence += "。"
    if len(sentence) > max_characters:
        return None
    return sentence


def render_stem_template(
    operation: str,
    span: str,
    *,
    max_characters: int = DEFAULT_STEM_MAX_CHARACTERS,
) -> str | None:
    """Deterministic stem: operation-anchored declaration with the predicted span."""
    templates = STEM_TEMPLATES.get(operation)
    if not templates:
        return None
    head = span.strip()
    if not head:
        return None
    head = re.sub(r"[。．.!！？?\s]+$", "", head)[:_SPAN_HEAD].strip()
    if not head:
        return None
    for template in templates:
        candidate = template.format(span=head)
        if len(candidate) <= max_characters:
            return candidate
    return None


def build_stem_messages(
    operation: str,
    *,
    text: str,
    span: str,
    context: Sequence[str] = (),
    max_characters: int = DEFAULT_STEM_MAX_CHARACTERS,
) -> tuple[str, str]:
    instruction = OPERATION_INSTRUCTIONS.get(operation, operation)
    recent = " / ".join(context[-4:]) or "なし"
    system = (
        "あなたは日本語の話し手を支援する、推論の初期条件を一文で書くことに長けた"
        "ファシリテーターです。出力は一文のみで、説明・引用符・箇条書きを含めません。"
    )
    user = (
        f"【直前までの文脈】\n{recent}\n\n"
        f"【現在の発話】\n{text}\n\n"
        f"【次に来ると予測される節】\n{span}\n\n"
        f"この文脈で、話し手がこれから言うべき「{instruction}」を体現する、"
        "最も妥当な一文を書いてください。\n"
        "条件:\n"
        f"- {max_characters}文字以内の自然な日本語の宣言文であること\n"
        "- 話し手がそのまま採用して続きを話せる形であること\n"
        "- 事実を断定しすぎず、推量・限定を含んでよいこと\n"
        "- 改行・引用符・説明・記号の列挙を含めないこと\n"
        "- 出力は一文のみ\n"
        "文:\n"
    )
    return system, user


class StemCueGenerator:
    """Write one context-grounded initial-condition sentence per decision.

    LLM first (one short chat completion), predicted-span template second,
    None third — the caller then falls back to the bare wording. Latency is
    bounded by ``timeout``; the decision never blocks forever on the model.
    """

    def __init__(
        self,
        *,
        base_url: str = "http://127.0.0.1:11434",
        model: str | None = None,
        timeout: float = 1.5,
        max_tokens: int = 160,
        max_characters: int = DEFAULT_STEM_MAX_CHARACTERS,
        temperature: float = 0.0,
    ) -> None:
        if timeout <= 0:
            raise ValueError("timeout must be positive")
        if max_tokens < 1:
            raise ValueError("max_tokens must be positive")
        if max_characters < 8:
            raise ValueError("max_characters must be at least 8")
        self.base_url = base_url.rstrip("/")
        self.model = model or resolve_model(
            self.base_url, timeout=max(timeout, 5.0), preferred=PREFERRED_DECISION_MODELS
        )
        self.timeout = timeout
        self.max_tokens = max_tokens
        self.max_characters = max_characters
        self.temperature = temperature
        self.label = f"stem-llm({self.model})"
        self.last_error: str | None = None

    def warmup(self) -> None:
        """Load the model so the first stem is not slowed by a cold start."""
        try:
            self._complete([{"role": "user", "content": "ping"}], max_tokens=1)
        except RuntimeError:
            pass

    def _complete(
        self, messages: list[dict[str, str]], *, max_tokens: int | None = None
    ) -> str:
        request_body = {
            "model": self.model,
            "messages": messages,
            "temperature": self.temperature,
            "max_tokens": max_tokens or self.max_tokens,
            "stream": False,
        }
        request = urllib.request.Request(
            self.base_url + "/v1/chat/completions",
            data=json.dumps(request_body).encode("utf-8"),
            headers={"Content-Type": "application/json"},
            method="POST",
        )
        try:
            with urllib.request.urlopen(request, timeout=self.timeout) as response:
                body = json.loads(response.read().decode("utf-8"))
        except Exception as exc:
            raise RuntimeError(f"stem request failed: {exc}") from exc
        try:
            return str(body["choices"][0]["message"]["content"])
        except (KeyError, IndexError, TypeError) as exc:
            raise RuntimeError(f"unexpected stem payload: {exc}") from exc

    def generate(
        self,
        operation: str,
        *,
        text: str,
        span: str,
        context: Sequence[str] = (),
    ) -> str | None:
        try:
            system, user = build_stem_messages(
                operation,
                text=text,
                span=span,
                context=context,
                max_characters=self.max_characters,
            )
            content = self._complete(
                [
                    {"role": "system", "content": system},
                    {"role": "user", "content": user},
                ]
            )
        except (RuntimeError, TypeError, ValueError) as exc:
            self.last_error = str(exc)
            sentence = None
        else:
            sentence = finalize_stem(content, max_characters=self.max_characters)
            self.last_error = None if sentence else "stem response was not a usable sentence"
        if sentence is not None:
            return sentence
        return render_stem_template(operation, span, max_characters=self.max_characters)
